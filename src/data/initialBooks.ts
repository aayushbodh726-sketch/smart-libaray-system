// Helper for dates relative to today
const getRelativeDateString = (daysOffset: number): { display: string; iso: string } => {
  const d = new Date();
  d.setDate(d.getDate() + daysOffset);
  const iso = d.toISOString().split('T')[0];
  const display = d.toLocaleDateString('en-US', { month: 'short', day: '2-digit', year: 'numeric' });
  return { display, iso };
};

